"""Train the selected matcher only on separately reviewed private inputs.

No subject allocation, comparison generation or final-test scoring is performed.
Use the documented review receipt; no review assertion is generated by this CLI.
"""

import argparse
import csv
from importlib import metadata
import os
from pathlib import Path
import platform
import subprocess
import sys

from precise_matching.data import InputError
from precise_matching.encoders import CONFIG_SHA256, MODEL_ID, REVISION, WEIGHTS_SHA256, load_encoder
from precise_matching.images import image_tensor, prepare_image
from precise_matching.training import digest, reviewed_inputs, train

ROOT = Path(__file__).resolve().parents[1]


def git_output(*args, text=False):
    return subprocess.check_output(["git", *args], cwd=ROOT, text=text)


def package_versions():
    return {name: metadata.version(name) for name in
            ("torch", "transformers", "numpy", "Pillow", "safetensors")}


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ("images", "pairs", "paths", "config", "review", "source-root", "weights", "output"):
        parser.add_argument("--" + name, type=Path, required=True)
    parser.add_argument("--resume", type=Path)
    args = parser.parse_args(argv)
    try:
        output = args.output.resolve()
        if not output.is_relative_to(ROOT / "local/precise/runs"):
            raise InputError("Training outputs must remain under local/precise/runs/.")
        images, pairs, paths, config, input_hashes, input_integrity = reviewed_inputs(
            args.images, args.pairs, args.paths, args.config, args.review, args.source_root)
        code = sorted((ROOT / "code/precise_matching").glob("*.py")) + [ROOT / "code/train_precise_matcher.py"]
        source_hashes = {str(p.relative_to(ROOT)): digest(p) for p in code}
        changes = git_output("status", "--porcelain", "--untracked-files=all", "--",
                             "code/precise_matching", "code/train_precise_matcher.py")
        if changes.strip():
            raise InputError("Commit and review matcher source before a real run.")

        def integrity():
            input_integrity()
            if any(digest(ROOT / name) != value for name, value in source_hashes.items()):
                raise InputError("Matcher source changed during execution.")

        integrity()
        os.environ["HF_HUB_OFFLINE"] = "1"
        os.environ["TRANSFORMERS_OFFLINE"] = "1"
        os.environ["CUBLAS_WORKSPACE_CONFIG"] = ":4096:8"
        provenance = {"code_commit": git_output("rev-parse", "HEAD", text=True).strip(),
            "source_sha256": source_hashes, "input_sha256": input_hashes,
            "input_paths": {name: str(getattr(args, name).resolve())
                            for name in ("images", "pairs", "paths", "config", "review")},
            "source_root": str(args.source_root.resolve()),
            "weights_path": str(args.weights.resolve()),
            "model": MODEL_ID, "model_revision": REVISION,
            "weights_sha256": WEIGHTS_SHA256, "model_config_sha256": CONFIG_SHA256,
            "environment_lock_sha256": digest(ROOT / "code/precise_matching/environment/requirements-linux-x86_64-py312-cu124.lock"),
            "python": platform.python_version(),
            "packages": package_versions()}
        model = load_encoder(args.weights, adapted=True, device=config.device)
        import torch
        provenance["hardware"] = {"device": config.device, "platform": platform.platform(),
            "torch_runtime": str(torch.__version__), "torch_compiled_cuda": torch.version.cuda,
            "cuda_device": torch.cuda.get_device_name() if config.device == "cuda" else None}

        def load(row):
            if row.partition not in {"train", "development"}:
                raise InputError("Final-test images cannot enter the training loader.")
            return image_tensor(prepare_image(paths[row.image_id], row.sha256, row.decoded_sha256))

        train(model, images, pairs, load, config, output, provenance,
              integrity=integrity, resume=args.resume)
    except (InputError, OSError, ValueError, TypeError, KeyError, RuntimeError,
            ImportError, csv.Error, subprocess.SubprocessError):
        print("Training did not complete. Inspect private review/runtime records; no test scoring was performed.",
              file=sys.stderr)
        return 1
    print("Training attempt complete; private development-selected artifacts preserved. No test scoring performed.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
